"""Generate src/render/star_catalog.inc from the vendored bright-star catalogue
(SPEC A165).

Source: assets/sky/stars.6.json from d3-celestial by Olaf Frohn (BSD 3-Clause,
assets/sky/LICENSE-d3-celestial; commit 7e720a3 of ofrohn/d3-celestial), every
star to visual magnitude 6 (5,044, Hipparcos-derived) as GeoJSON points with
[longitude, latitude] = [right ascension wrapped to +-180 deg, declination] in
degrees, J2000 (ICRF), plus V magnitude and B-V colour index. Two stars carry
no colour index; they are written as 0.65 (Sun-like white).

Usage: python3 tools/stars.py [--check]
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "sky" / "stars.6.json"
LICENSE = ROOT / "assets" / "sky" / "LICENSE-d3-celestial"
OUTPUT = ROOT / "src" / "render" / "star_catalog.inc"


def generate() -> str:
    features = json.loads(SOURCE.read_text())["features"]
    rows = []
    for feature in features:
        ra, dec = feature["geometry"]["coordinates"]
        props = feature["properties"]
        bv = props.get("bv")
        bv = float(bv) if bv not in (None, "") else 0.65
        rows.append(f"    {{{ra % 360:.4f}f, {dec:.4f}f, {float(props['mag']):.2f}f, {bv:.3f}f}},")
    notice = "\n".join(" * " + line if line else " *" for line in LICENSE.read_text().strip().splitlines())
    return (
        "/* Generated by tools/stars.py from assets/sky/stars.6.json; do not edit.\n"
        " * Stars to visual magnitude 6: right ascension and declination in degrees\n"
        " * (J2000/ICRF), V magnitude and B-V colour index. Data from d3-celestial:\n *\n"
        f"{notice}\n */\n"
        f"#define RENDER_STAR_COUNT {len(rows)}\n"
        "static const float star_catalog[RENDER_STAR_COUNT][4] = {\n"
        + "\n".join(rows) + "\n};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    text = generate()
    if parser.parse_args().check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run tools/stars.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} matches the source")
        return 0
    OUTPUT.write_text(text)
    print(f"{OUTPUT.relative_to(ROOT)}: {text.count('f},')} stars")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
