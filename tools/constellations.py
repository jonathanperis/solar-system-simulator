"""Generate src/render/constellation_lines.inc from the vendored IAU
constellation stick figures (SPEC A124).

Source: assets/sky/constellations.lines.json from d3-celestial by Olaf Frohn
(BSD 3-Clause, assets/sky/LICENSE-d3-celestial), a GeoJSON MultiLineString
per constellation with [longitude, latitude] = [right ascension wrapped to
+-180 deg, declination] in degrees, J2000 (ICRF).

Usage: python3 tools/constellations.py [--check]
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "sky" / "constellations.lines.json"
LICENSE = ROOT / "assets" / "sky" / "LICENSE-d3-celestial"
OUTPUT = ROOT / "src" / "render" / "constellation_lines.inc"


def generate() -> str:
    features = json.loads(SOURCE.read_text())["features"]
    rows = []
    for feature in features:
        for line in feature["geometry"]["coordinates"]:
            for (ra0, dec0), (ra1, dec1) in zip(line, line[1:]):
                rows.append(f"    {{{ra0 % 360:.4f}f, {dec0:.4f}f, {ra1 % 360:.4f}f, {dec1:.4f}f}}, /* {feature['id']} */")
    notice = "\n".join(" * " + line if line else " *" for line in LICENSE.read_text().strip().splitlines())
    return (
        "/* Generated by tools/constellations.py from assets/sky/constellations.lines.json; do not edit.\n"
        " * IAU constellation stick figures: segment endpoints as right ascension and\n"
        " * declination in degrees (J2000/ICRF). Data from d3-celestial:\n *\n"
        f"{notice}\n */\n"
        f"#define RENDER_CONSTELLATION_SEGMENTS {len(rows)}\n"
        "static const float constellation_segments[RENDER_CONSTELLATION_SEGMENTS][4] = {\n"
        + "\n".join(rows) + "\n};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    text = generate()
    if parser.parse_args().check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run tools/constellations.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} matches the source")
        return 0
    OUTPUT.write_text(text)
    print(f"{OUTPUT.relative_to(ROOT)}: {text.count('/* ', 1) and text.count('}, /*')} segments")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
